import json
import os
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse, urlunparse

import psycopg
from psycopg.rows import dict_row


PROJECT_ROOT = Path(__file__).resolve().parent.parent
DB_PATH = PROJECT_ROOT / "artifacts" / "transactions.db"

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()

if DATABASE_URL:
    parsed_url = urlparse(DATABASE_URL)
    if parsed_url.scheme not in ("postgres", "postgresql"):
        raise ValueError("DATABASE_URL must be a PostgreSQL connection URL.")
    if not parsed_url.hostname or not parsed_url.path:
        raise ValueError("DATABASE_URL is missing the database host or name.")


def get_connection():
    if DATABASE_URL:
        return psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=15,
            sslmode="require",
        )

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(DB_PATH, timeout=30)
    connection.row_factory = sqlite3.Row
    return connection


def initialize_database():
    with get_connection() as connection:
        if DATABASE_URL:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS transactions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    transaction_data TEXT NOT NULL,
                    amount DOUBLE PRECISION NOT NULL,
                    prediction INTEGER NOT NULL,
                    label TEXT NOT NULL,
                    fraud_probability DOUBLE PRECISION NOT NULL,
                    threshold DOUBLE PRECISION NOT NULL,
                    created_at TEXT NOT NULL
                )
                """
            )
        else:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS transactions (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    transaction_data TEXT NOT NULL,
                    amount REAL NOT NULL,
                    prediction INTEGER NOT NULL,
                    label TEXT NOT NULL,
                    fraud_probability REAL NOT NULL,
                    threshold REAL NOT NULL,
                    created_at TEXT NOT NULL
                )
                """
            )


def save_transaction(transaction_data, result):
    required_fields = (
        "Amount",
    )

    for field in required_fields:
        if field not in transaction_data:
            raise ValueError(f"Missing transaction field: {field}")

    required_results = (
        "prediction",
        "label",
        "fraud_probability",
        "threshold",
    )

    for field in required_results:
        if field not in result:
            raise ValueError(f"Missing prediction result field: {field}")

    created_at = datetime.now(timezone.utc).isoformat()

    values = (
        json.dumps(transaction_data),
        float(transaction_data["Amount"]),
        int(result["prediction"]),
        str(result["label"]),
        float(result["fraud_probability"]),
        float(result["threshold"]),
        created_at,
    )

    with get_connection() as connection:
        if DATABASE_URL:
            cursor = connection.execute(
                """
                INSERT INTO transactions (
                    transaction_data,
                    amount,
                    prediction,
                    label,
                    fraud_probability,
                    threshold,
                    created_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                RETURNING id
                """,
                values,
            )
            row = cursor.fetchone()
            return row["id"]

        cursor = connection.execute(
            """
            INSERT INTO transactions (
                transaction_data,
                amount,
                prediction,
                label,
                fraud_probability,
                threshold,
                created_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            values,
        )
        return cursor.lastrowid


def get_transaction_history(limit=100):
    limit = max(1, min(int(limit), 1000))

    with get_connection() as connection:
        if DATABASE_URL:
            rows = connection.execute(
                """
                SELECT *
                FROM transactions
                ORDER BY id DESC
                LIMIT %s
                """,
                (limit,),
            ).fetchall()
        else:
            rows = connection.execute(
                """
                SELECT *
                FROM transactions
                ORDER BY id DESC
                LIMIT ?
                """,
                (limit,),
            ).fetchall()

    return [
        {
            "id": row["id"],
            "transaction_data": json.loads(row["transaction_data"]),
            "amount": row["amount"],
            "prediction": row["prediction"],
            "label": row["label"],
            "fraud_probability": row["fraud_probability"],
            "threshold": row["threshold"],
            "created_at": row["created_at"],
        }
        for row in rows
    ]